#!/bin/env python3

import os

from die import die

GITIGNORE_HEAD = """
/**
!.gitignore
"""
ROOT = os.getenv("HOME") or die("Not found HOME directory")


from pathlib import Path, PurePath

from white_list import white_list_path

dir_set: set[PurePath] = set()
path_list: list[str] = []


def append_parent_path(path: PurePath):
    if path == ".":
        return
    else:
        mark = path.parent / "*"
        if not mark in dir_set:
            dir_set.add(mark)
            append_parent_path(path.parent)


def main():
    for path in white_list_path():
        path_list.append(path)
        append_parent_path(Path(path).parent)
    with open(ROOT + "/.gitignore", "w", encoding="utf-8") as f:
        f.write(f"# Generated by {__file__}\n")
        f.write(GITIGNORE_HEAD)
        f.writelines(f"!/{d}/\n" for d in sorted(dir_set))
        f.writelines(f"!/{p}\n" for p in sorted(path_list))
        f.write("# End of Generation\n")


main()
